package proxy

// Staged configs. Caddy (and fog-wire) read their config from a directory
// fog keeps, <dir>/conf, mounted at /etc/caddy. A new config is written
// beside the live one as Caddyfile.next, validated by the Caddy that will
// run it, and only then renamed over Caddyfile — one rename, so a reader
// sees the old file or the new, and a config Caddy rejected is never where
// a restart would load it. Until a first config is accepted, the live file
// is an empty one Caddy runs happily.

import (
	"errors"
	"os"
	"path/filepath"

	"gitea.lan/matthew/fog/internal/fsx"
)

const stagedName = "Caddyfile.next"

func confDir(dir string) string { return filepath.Join(dir, "conf") }

// stageConfig writes conf as the staged config, making the live one boot
// (a config with nothing but the admin endpoint conf's reload will look
// for) if there is none yet.
func stageConfig(dir string, conf []byte, boot ...string) error {
	cd := confDir(dir)
	if err := os.MkdirAll(cd, 0o755); err != nil {
		return err
	}
	live := filepath.Join(cd, "Caddyfile")
	if _, err := os.Stat(live); errors.Is(err, os.ErrNotExist) {
		b := "# Generated by Fog: no config accepted yet.\n"
		for _, l := range boot {
			b += l
		}
		if err := fsx.WriteFileAtomic(live, []byte(b), 0o644); err != nil {
			return err
		}
	}
	return fsx.WriteFileAtomic(filepath.Join(cd, stagedName), conf, 0o644)
}

// promoteStaged renames the staged config over the live one, once it is
// accepted. Nothing staged (already promoted) is no error.
func promoteStaged(dir string) error {
	err := os.Rename(filepath.Join(confDir(dir), stagedName), filepath.Join(confDir(dir), "Caddyfile"))
	if errors.Is(err, os.ErrNotExist) {
		return nil
	}
	// The file the old layout bind-mounted on its own is no longer read.
	os.Remove(filepath.Join(dir, "Caddyfile"))
	os.Remove(filepath.Join(dir, "Wirefile"))
	return err
}

// discardStaged drops a staged config that wasn't accepted.
func discardStaged(dir string) { os.Remove(filepath.Join(confDir(dir), stagedName)) }
