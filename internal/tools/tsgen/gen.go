// Command tsgen writes TypeScript declarations for the Go structs fog's JSON
// APIs encode, so the clients' types come from the structs themselves
// instead of a hand-kept mirror that drifts: frontend/src/api.gen.ts for
// fogd's API, frontend/setup/types.gen.ts for the installer's, and
// clients/chat-sdk/src/wire.gen.ts for the chat endpoints the SDK calls
// (outputs, in roots.go).
//
// It reads Go source (not compiled types) so it can follow unexported view
// structs and carry doc comments across, and it mirrors encoding/json's
// rules: json tags name and hide fields, omitempty/omitzero make a field
// optional, untagged embedded structs are flattened (the shallowest field
// of a name wins), and a nil pointer field without omitempty is null. Nil
// slices, maps, embedded pointers and pointer elements are typed as
// present: handlers that encode them are expected to send [] and {}.
//
// A string type with typed constants in its package becomes a union of
// those constants. A field whose TypeScript type is narrower than its Go
// type carries a `ts:"…"` tag with the TypeScript to emit.
//
// A key set is the other kind of root: a package-level map literal whose
// string keys become the fields of an interface, for an endpoint that
// encodes a map[string]string built from that map's keys (fogd's settings).
//
//	go run ./internal/tools/tsgen            # rewrite the files
//	go test ./internal/tools/tsgen           # fail if one is stale
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/build"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"reflect"
	"strconv"
	"strings"
)

const modulePath = "gitea.lan/matthew/fog"

func main() {
	root, err := moduleRoot()
	if err != nil {
		fmt.Fprintln(os.Stderr, "tsgen:", err)
		os.Exit(1)
	}
	for _, o := range outputs {
		out, err := generate(root, o)
		if err != nil {
			fmt.Fprintln(os.Stderr, "tsgen:", o.File+":", err)
			os.Exit(1)
		}
		if err := os.WriteFile(filepath.Join(root, o.File), out, 0o644); err != nil {
			fmt.Fprintln(os.Stderr, "tsgen:", err)
			os.Exit(1)
		}
	}
}

// moduleRoot walks up from the working directory to go.mod.
func moduleRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", fmt.Errorf("no go.mod above the working directory")
		}
		dir = parent
	}
}

// generate renders one output: every root type and everything they
// reference, then its key sets. Each output is its own namespace: a type
// two of them reference is declared in both.
func generate(root string, o output) ([]byte, error) {
	g := newGen(root)
	for _, r := range o.Roots {
		if _, err := g.named(r.key(), r.TS); err != nil {
			return nil, err
		}
	}
	for len(g.queue) > 0 {
		k := g.queue[0]
		g.queue = g.queue[1:]
		if err := g.emit(k); err != nil {
			return nil, err
		}
	}
	for _, ks := range o.Keys {
		if err := g.keySet(ks); err != nil {
			return nil, err
		}
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by internal/tools/tsgen from fog's Go structs. DO NOT EDIT.\n")
	b.WriteString("// Change the Go struct (or its ts:\"…\" tag) and run `make gen-types`.\n")
	for _, d := range g.decls {
		b.WriteString("\n")
		b.WriteString(d)
	}
	return b.Bytes(), nil
}

type typeKey struct{ path, name string }

func (k typeKey) String() string { return k.path + "." + k.name }

type pkg struct {
	path      string
	name      string
	fset      *token.FileSet
	types     map[string]*ast.TypeSpec
	docs      map[string]*ast.CommentGroup // type and var doc comments (GenDecl doc for single specs)
	files     map[ast.Node]*ast.File       // type and var specs → their file
	consts    map[string][]string          // named type → its string constants, in source order
	strConsts map[string]string            // every string constant → its value, for key sets
	vars      map[string]*ast.ValueSpec
	marshal   map[string]bool // types with their own MarshalJSON
}

type gen struct {
	root    string
	pkgs    map[string]*pkg
	emitted map[typeKey]string // type → its TS name
	names   map[string]typeKey // TS name → type, to refuse collisions
	queue   []typeKey
	decls   []string
}

func newGen(root string) *gen {
	return &gen{root: root, pkgs: map[string]*pkg{}, emitted: map[typeKey]string{}, names: map[string]typeKey{}}
}

// named returns the TS name for a named Go type, queueing its declaration.
func (g *gen) named(k typeKey, tsName string) (string, error) {
	if name, ok := g.emitted[k]; ok {
		return name, nil
	}
	p, err := g.load(k.path)
	if err != nil {
		return "", err
	}
	if _, ok := p.types[k.name]; !ok {
		return "", fmt.Errorf("%s: no such type", k)
	}
	if tsName == "" {
		tsName = renames[k.String()]
	}
	if tsName == "" {
		// An unexported view struct reads as its exported spelling.
		tsName = strings.ToUpper(k.name[:1]) + k.name[1:]
	}
	if other, ok := g.names[tsName]; ok && other != k {
		return "", fmt.Errorf("%s and %s would both be %s: add a rename", other, k, tsName)
	}
	g.names[tsName] = k
	g.emitted[k] = tsName
	g.queue = append(g.queue, k)
	return tsName, nil
}

func (g *gen) load(path string) (*pkg, error) {
	if p, ok := g.pkgs[path]; ok {
		return p, nil
	}
	if !strings.HasPrefix(path, modulePath+"/") {
		return nil, fmt.Errorf("%s is outside the module", path)
	}
	dir := filepath.Join(g.root, strings.TrimPrefix(path, modulePath+"/"))
	// Linux is where fogd runs: platform files resolve as they do there.
	ctxt := build.Default
	ctxt.GOOS, ctxt.GOARCH = "linux", "amd64"
	bp, err := ctxt.ImportDir(dir, 0)
	if err != nil {
		return nil, err
	}
	fset := token.NewFileSet()
	p := &pkg{path: path, name: bp.Name, fset: fset, types: map[string]*ast.TypeSpec{}, docs: map[string]*ast.CommentGroup{},
		files: map[ast.Node]*ast.File{}, consts: map[string][]string{}, strConsts: map[string]string{},
		vars: map[string]*ast.ValueSpec{}, marshal: map[string]bool{}}
	for _, name := range bp.GoFiles {
		f, err := parser.ParseFile(fset, filepath.Join(dir, name), nil, parser.ParseComments)
		if err != nil {
			return nil, err
		}
		for _, decl := range f.Decls {
			switch d := decl.(type) {
			case *ast.GenDecl:
				p.index(f, d)
			case *ast.FuncDecl:
				if d.Name.Name == "MarshalJSON" && d.Recv != nil && len(d.Recv.List) == 1 {
					p.marshal[recvName(d.Recv.List[0].Type)] = true
				}
			}
		}
	}
	g.pkgs[path] = p
	return p, nil
}

func (p *pkg) index(f *ast.File, d *ast.GenDecl) {
	switch d.Tok {
	case token.TYPE:
		for _, s := range d.Specs {
			ts := s.(*ast.TypeSpec)
			p.types[ts.Name.Name] = ts
			p.files[ts] = f
			doc := ts.Doc
			if doc == nil && len(d.Specs) == 1 {
				doc = d.Doc
			}
			p.docs[ts.Name.Name] = doc
		}
	case token.CONST:
		for _, s := range d.Specs {
			vs := s.(*ast.ValueSpec)
			if len(vs.Values) != len(vs.Names) {
				continue
			}
			id, typed := vs.Type.(*ast.Ident)
			for i, v := range vs.Values {
				if lit, ok := v.(*ast.BasicLit); ok && lit.Kind == token.STRING {
					if s, err := strconv.Unquote(lit.Value); err == nil {
						p.strConsts[vs.Names[i].Name] = s
						if typed {
							p.consts[id.Name] = append(p.consts[id.Name], s)
						}
					}
				}
			}
		}
	case token.VAR:
		for _, s := range d.Specs {
			vs := s.(*ast.ValueSpec)
			for _, n := range vs.Names {
				p.vars[n.Name] = vs
			}
			p.files[vs] = f
			doc := vs.Doc
			if doc == nil && len(d.Specs) == 1 {
				doc = d.Doc
			}
			for _, n := range vs.Names {
				p.docs[n.Name] = doc
			}
		}
	}
}

func recvName(e ast.Expr) string {
	if s, ok := e.(*ast.StarExpr); ok {
		e = s.X
	}
	if id, ok := e.(*ast.Ident); ok {
		return id.Name
	}
	return ""
}

// emit renders one queued declaration.
func (g *gen) emit(k typeKey) error {
	p := g.pkgs[k.path]
	ts := p.types[k.name]
	name := g.emitted[k]
	if p.marshal[k.name] {
		return fmt.Errorf("%s has its own MarshalJSON: describe it by hand instead", k)
	}
	if ts.TypeParams != nil {
		return fmt.Errorf("%s is generic", k)
	}
	var b strings.Builder
	writeComment(&b, p.docs[k.name], "")
	switch t := ts.Type.(type) {
	case *ast.StructType:
		fields, err := g.fields(p, p.files[ts], t, "  ")
		if err != nil {
			return fmt.Errorf("%s: %w", k, err)
		}
		fmt.Fprintf(&b, "export interface %s {\n%s}\n", name, fields)
	default:
		if vals := p.consts[k.name]; len(vals) > 0 {
			fmt.Fprintf(&b, "export type %s = %s;\n", name, union(vals))
			break
		}
		expr, err := g.expr(p, p.files[ts], ts.Type, "")
		if err != nil {
			return fmt.Errorf("%s: %w", k, err)
		}
		fmt.Fprintf(&b, "export type %s = %s;\n", name, expr)
	}
	g.decls = append(g.decls, b.String())
	return nil
}

func union(vals []string) string {
	seen := map[string]bool{}
	var parts []string
	for _, v := range vals {
		if !seen[v] {
			seen[v] = true
			parts = append(parts, strconv.Quote(v))
		}
	}
	return strings.Join(parts, " | ")
}

// member is one rendered field, with what encoding/json needs to decide
// which of several same-named fields wins.
type member struct {
	name   string
	depth  int // embedding depth: 0 is the struct's own field
	tagged bool
	text   string
}

// fields renders a struct's members, flattening untagged embedded structs.
// Like encoding/json, the shallowest field of a name wins; at equal depth a
// tagged field beats untagged ones, and otherwise the name is dropped.
func (g *gen) fields(p *pkg, f *ast.File, st *ast.StructType, indent string) (string, error) {
	var all []member
	if err := g.fieldsInto(&all, p, f, st, indent, 0); err != nil {
		return "", err
	}
	byName := map[string][]member{}
	for _, m := range all {
		byName[m.name] = append(byName[m.name], m)
	}
	var b strings.Builder
	for _, m := range all {
		if winner(byName[m.name]) == m.depth && winnerTagged(byName[m.name], m) {
			b.WriteString(m.text)
		}
	}
	return b.String(), nil
}

func winner(ms []member) int {
	best := ms[0].depth
	for _, m := range ms[1:] {
		best = min(best, m.depth)
	}
	return best
}

// winnerTagged reports whether m is the one field encoding/json keeps among
// the shallowest of its name.
func winnerTagged(ms []member, m member) bool {
	var top []member
	for _, x := range ms {
		if x.depth == m.depth {
			top = append(top, x)
		}
	}
	if len(top) == 1 {
		return true
	}
	var tagged []member
	for _, x := range top {
		if x.tagged {
			tagged = append(tagged, x)
		}
	}
	return len(tagged) == 1 && m.tagged
}

func (g *gen) fieldsInto(out *[]member, p *pkg, f *ast.File, st *ast.StructType, indent string, depth int) error {
	for _, fld := range st.Fields.List {
		tag := reflect.StructTag("")
		if fld.Tag != nil {
			raw, err := strconv.Unquote(fld.Tag.Value)
			if err != nil {
				return err
			}
			tag = reflect.StructTag(raw)
		}
		jsonName, opts, _ := strings.Cut(tag.Get("json"), ",")
		if jsonName == "-" && opts == "" {
			continue
		}
		if len(fld.Names) == 0 { // embedded
			if jsonName == "" {
				// An embedded pointer's fields are typed as present: fog
				// never embeds a nil one in what it encodes.
				ep, ef, est, err := g.embedded(p, f, fld.Type)
				if err != nil {
					return err
				}
				if est != nil {
					if err := g.fieldsInto(out, ep, ef, est, indent, depth+1); err != nil {
						return err
					}
					continue
				}
			}
			name := typeName(fld.Type)
			if !ast.IsExported(name) {
				continue
			}
			tagged := jsonName != ""
			if !tagged {
				jsonName = name
			}
			text, err := g.member(p, f, fld, jsonName, opts, tag, indent)
			if err != nil {
				return err
			}
			*out = append(*out, member{jsonName, depth, tagged, text})
			continue
		}
		for _, id := range fld.Names {
			if !id.IsExported() {
				continue
			}
			name := jsonName
			if name == "" {
				name = id.Name
			}
			text, err := g.member(p, f, fld, name, opts, tag, indent)
			if err != nil {
				return err
			}
			*out = append(*out, member{name, depth, jsonName != "", text})
		}
	}
	return nil
}

func (g *gen) member(p *pkg, f *ast.File, fld *ast.Field, name, opts string, tag reflect.StructTag, indent string) (string, error) {
	var b strings.Builder
	omit := hasOpt(opts, "omitempty") || hasOpt(opts, "omitzero")
	typ := fld.Type
	ptr := false
	if s, ok := typ.(*ast.StarExpr); ok {
		ptr, typ = true, s.X
	}
	var expr string
	if override, ok := tag.Lookup("ts"); ok {
		expr = override
	} else if hasOpt(opts, "string") {
		expr = "string"
	} else {
		var err error
		if expr, err = g.expr(p, f, typ, indent); err != nil {
			return "", fmt.Errorf("field %s: %w", name, err)
		}
	}
	// omitempty never drops a struct value, only omitzero does.
	optional := omit && (ptr || !isStructValue(g, p, f, typ) || hasOpt(opts, "omitzero"))
	if ptr && !omit && !strings.Contains(expr, "null") {
		expr += " | null"
	}
	writeComment(&b, fld.Doc, indent)
	q := ""
	if optional {
		q = "?"
	}
	fmt.Fprintf(&b, "%s%s%s: %s;", indent, fieldKey(name), q, expr)
	if fld.Comment != nil {
		fmt.Fprintf(&b, " // %s", strings.TrimSpace(fld.Comment.Text()))
	}
	b.WriteString("\n")
	return b.String(), nil
}

func hasOpt(opts, want string) bool {
	for _, o := range strings.Split(opts, ",") {
		if o == want {
			return true
		}
	}
	return false
}

func isIdent(s string) bool {
	for i, r := range s {
		if !(r == '_' || r == '$' || r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || i > 0 && r >= '0' && r <= '9') {
			return false
		}
	}
	return s != ""
}

func typeName(e ast.Expr) string {
	switch t := e.(type) {
	case *ast.StarExpr:
		return typeName(t.X)
	case *ast.Ident:
		return t.Name
	case *ast.SelectorExpr:
		return t.Sel.Name
	}
	return ""
}

// embedded resolves an embedded field to its struct, if it is one.
func (g *gen) embedded(p *pkg, f *ast.File, e ast.Expr) (*pkg, *ast.File, *ast.StructType, error) {
	if s, ok := e.(*ast.StarExpr); ok {
		e = s.X
	}
	k, ok, err := g.resolve(p, f, e)
	if err != nil || !ok {
		return nil, nil, nil, err
	}
	tp, err := g.load(k.path)
	if err != nil {
		return nil, nil, nil, err
	}
	ts, ok := tp.types[k.name]
	if !ok {
		return nil, nil, nil, fmt.Errorf("%s: no such type", k)
	}
	st, ok := ts.Type.(*ast.StructType)
	if !ok {
		return nil, nil, nil, nil
	}
	return tp, tp.files[ts], st, nil
}

func isStructValue(g *gen, p *pkg, f *ast.File, e ast.Expr) bool {
	if _, ok := e.(*ast.StructType); ok {
		return true
	}
	k, ok, err := g.resolve(p, f, e)
	if err != nil || !ok {
		return false
	}
	if k.path == "time" && k.name == "Time" {
		return true
	}
	tp, err := g.load(k.path)
	if err != nil {
		return false
	}
	ts, ok := tp.types[k.name]
	if !ok {
		return false
	}
	_, isStruct := ts.Type.(*ast.StructType)
	return isStruct
}

// resolve names the type an identifier or selector refers to. ok is false
// for predeclared types.
func (g *gen) resolve(p *pkg, f *ast.File, e ast.Expr) (typeKey, bool, error) {
	switch t := e.(type) {
	case *ast.Ident:
		if _, ok := p.types[t.Name]; ok {
			return typeKey{p.path, t.Name}, true, nil
		}
		return typeKey{}, false, nil
	case *ast.SelectorExpr:
		x, ok := t.X.(*ast.Ident)
		if !ok {
			return typeKey{}, false, fmt.Errorf("unsupported selector")
		}
		path, err := g.importPath(f, x.Name)
		if err != nil {
			return typeKey{}, false, err
		}
		return typeKey{path, t.Sel.Name}, true, nil
	}
	return typeKey{}, false, nil
}

func (g *gen) importPath(f *ast.File, local string) (string, error) {
	for _, imp := range f.Imports {
		path, _ := strconv.Unquote(imp.Path.Value)
		if imp.Name != nil {
			if imp.Name.Name == local {
				return path, nil
			}
			continue
		}
		name := path[strings.LastIndex(path, "/")+1:]
		if strings.HasPrefix(path, modulePath+"/") {
			p, err := g.load(path)
			if err != nil {
				return "", err
			}
			name = p.name
		}
		if name == local {
			return path, nil
		}
	}
	return "", fmt.Errorf("no import for %s", local)
}

// external maps types from outside the module to how encoding/json writes them.
var external = map[string]string{
	"time.Time":                "string",
	"time.Duration":            "number",
	"encoding/json.RawMessage": "unknown",
}

func (g *gen) expr(p *pkg, f *ast.File, e ast.Expr, indent string) (string, error) {
	switch t := e.(type) {
	case *ast.Ident:
		switch t.Name {
		case "string":
			return "string", nil
		case "bool":
			return "boolean", nil
		case "int", "int8", "int16", "int32", "int64", "uint", "uint8", "uint16", "uint32", "uint64",
			"float32", "float64", "byte", "rune", "uintptr":
			return "number", nil
		case "any":
			return "unknown", nil
		case "error":
			return "", fmt.Errorf("error values don't encode")
		}
		return g.named(typeKey{p.path, t.Name}, "")
	case *ast.SelectorExpr:
		k, _, err := g.resolve(p, f, t)
		if err != nil {
			return "", err
		}
		if ts, ok := external[k.String()]; ok {
			return ts, nil
		}
		if !strings.HasPrefix(k.path, modulePath+"/") {
			return "", fmt.Errorf("no mapping for %s", k)
		}
		return g.named(k, "")
	case *ast.StarExpr:
		// Slice elements and map values: fog never encodes a nil there.
		return g.expr(p, f, t.X, indent)
	case *ast.ArrayType:
		if id, ok := t.Elt.(*ast.Ident); ok && (id.Name == "byte" || id.Name == "uint8") && t.Len == nil {
			return "string", nil // base64
		}
		inner, err := g.expr(p, f, t.Elt, indent)
		if err != nil {
			return "", err
		}
		if strings.ContainsAny(inner, " |") {
			inner = "(" + inner + ")"
		}
		return inner + "[]", nil
	case *ast.MapType:
		v, err := g.expr(p, f, t.Value, indent)
		if err != nil {
			return "", err
		}
		return "Record<string, " + v + ">", nil
	case *ast.InterfaceType:
		return "unknown", nil
	case *ast.StructType:
		body, err := g.fields(p, f, t, indent+"  ")
		if err != nil {
			return "", err
		}
		return "{\n" + body + indent + "}", nil
	}
	return "", fmt.Errorf("unsupported type %T", e)
}

func writeComment(b *strings.Builder, cg *ast.CommentGroup, indent string) {
	if cg == nil {
		return
	}
	text := strings.TrimRight(cg.Text(), "\n")
	if text == "" {
		return
	}
	for _, line := range strings.Split(text, "\n") {
		if line == "" {
			fmt.Fprintf(b, "%s//\n", indent)
		} else {
			fmt.Fprintf(b, "%s// %s\n", indent, line)
		}
	}
}
